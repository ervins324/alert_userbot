// DrawText draws a string onto img at (startX, startY) with scale factor and color.
func DrawText(img *image.RGBA, text string, startX, startY int, scale int, col color.RGBA) {
	if scale <= 0 {
		scale = 1
	}
	cursorX := startX
	for _, r := range text {
		glyph, ok := basicGlyphs[r]
		if !ok {
			// Fallback placeholder block
			glyph = fontGlyph{0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F}
		}

		for row := 0; row < 7; row++ {
			b := glyph[row]
			for colIdx := 0; colIdx < 5; colIdx++ {
				// Bit is set if (b & (1 << (4 - colIdx))) != 0
				if (b & (1 << (4 - colIdx))) != 0 {
					for dy := 0; dy < scale; dy++ {
						for dx := 0; dx < scale; dx++ {
							px := cursorX + colIdx*scale + dx
							py := startY + row*scale + dy
							if px >= 0 && px < img.Rect.Dx() && py >= 0 && py < img.Rect.Dy() {
								img.SetRGBA(px, py, col)
							}
						}
					}
				}
			}
		}
		cursorX += 6 * scale
	}
}

// MeasureText returns the width and height of the rendered text in pixels.
func MeasureText(text string, scale int) (int, int) {
	if scale <= 0 {
		scale = 1
	}
	count := utf8.RuneCountInString(text)
	return count * 6 * scale, 7 * scale
}
